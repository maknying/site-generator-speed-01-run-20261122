// Optimised drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// A faithful reimplementation of the reference build, written for speed:
//  - one-pass HTML escaping (a single regex exec loop, no per-character replace),
//  - Markdown lexed and rendered in a single fused pass (no token array, no
//    double walk), inline rendering that escapes whole plain runs at once,
//  - slugify results cached per case (titles, tag names and heading texts
//    repeat heavily), manual char-level checks instead of per-line regexes,
//  - template rendering into a shared output array instead of string +=,
//  - each source's card computed once and reused by its page object.
// The semantics follow vendor/makefun-site exactly; where this file and the
// README differ, the reference code (as ported here) is the answer.

